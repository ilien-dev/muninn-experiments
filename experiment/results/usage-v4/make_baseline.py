#!/usr/bin/env python3
"""Render BASELINE.md from the counts files of one build (every figure is read from counts/).

  python -I make_baseline.py <build> [<first-label build>]
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
B = sys.argv[1]
B1 = sys.argv[2] if len(sys.argv) > 2 else B + '-first'


def load(sec, b=B):
    p = os.path.join(HERE, 'counts', '%s_%s.json' % (sec, b))
    return json.load(open(p)) if os.path.isfile(p) else None


def frac(a, b):
    return '%d / %d' % (a, b) if b else '%d / 0' % a


L = []
w = L.append
a, b, c, d, e = load('a_extract'), load('b_retire'), load('c_delivery'), load('d_removals'), load('e_perf')
w('# usage-v4 base figures')
w('')
w('Build `%s` (`%s`). Generated by `make_baseline.py` from `counts/*_%s.json`; every figure below '
  'is read from those files. Final labels unless marked "first labels".' % (B, (a or c or b)['binary_version'], B))
w('')
if a:
    w('## A. Extraction (`a_extract.py`, base source tree)')
    w('')
    w('| | design | held-out | all |')
    w('|---|---|---|---|')
    S = a['splits']
    g = lambda k1, k2: [S[s][k1][k2] for s in ('design', 'heldout', 'all')]
    em = lambda s: S[s]['precision_set']['emitted_by_label']
    w('| precision set: records | %s |' % ' | '.join(str(x) for x in g('precision_set', 'items')))
    w('| ...measurable (the 2 deadends are not) | %s |' % ' | '.join(str(x) for x in g('precision_set', 'measurable')))
    w('| ...emitted by extract_dump | %s |' % ' | '.join(str(x) for x in g('precision_set', 'emitted')))
    for lab, name in (('a', 'durable'), ('b', 'transient'), ('c', 'not the user\'s'), ('d', 'fragment')):
        w('| ...emitted, labelled %s | %s |' % (name, ' | '.join(str(em(s).get(lab, 0)) for s in ('design', 'heldout', 'all'))))
    w('| ...record precision (durable / emitted) | %s |' % ' | '.join(str(x) for x in g('precision_set', 'record_precision')))
    w('| ...other candidates in the same source turns | %s |' % ' | '.join(str(x) for x in g('precision_set', 'unlabelled_candidates_in_source_turns')))
    w('| recall set: messages | %s |' % ' | '.join(str(x) for x in g('recall_set', 'messages')))
    w('| ...durable messages | %s |' % ' | '.join(str(x) for x in g('recall_set', 'durable_messages')))
    w('| ...durable emitted | %s |' % ' | '.join(str(x) for x in g('recall_set', 'durable_emitted')))
    w('| ...recall | %s |' % ' | '.join(str(x) for x in g('recall_set', 'recall')))
    cc = lambda s, k: S[s]['recall_set']['candidates_by_class'].get(k, 0)
    for k, name in (('durable', 'carrying an anchor'), ('a_other', 'from a durable message, another sentence'), ('b', 'from a message with nothing durable'), ('c', 'from a message not typed by a person')):
        w('| ...candidates %s | %s |' % (name, ' | '.join(str(cc(s, k)) for s in ('design', 'heldout', 'all'))))
    w('| ...message-level precision | %s |' % ' | '.join(str(x) for x in g('recall_set', 'message_precision')))
    w('')
    ta = a['turn_alignment']
    w('Fidelity: of the 107 measurable typed records the base source tree re-emits %d. Of %d candidates at recall turns, '
      '%d begin with text found in the message they are attributed to.' % (S['all']['precision_set']['emitted'], ta['candidates_at_recall_turns'], ta['text_found_in_message']))
    a1 = load('a_extract', B1)
    if a1:
        s1 = a1['splits']['all']
        w('First labels: emitted records labelled durable %d of %d emitted (plus %d deadend), so %d of 109 durable as in the analysis; '
          'recall set %d durable messages, of which the store held a carrying record for %d.' % (
              s1['precision_set']['emitted_by_label'].get('a', 0), s1['precision_set']['emitted'], s1['precision_set']['labels'].get('a', 0) - s1['precision_set']['emitted_by_label'].get('a', 0),
              s1['precision_set']['labels'].get('a', 0), s1['recall_set']['durable_messages'], s1['recall_set'].get('store_held_a_carrying_record', 0)))
    w('')
if b:
    S = b['splits']['all']
    w('## B. Retirement (`b_retire.py`)')
    w('')
    if 'b1' in S:
        x = S['b1']
        w('B1, replay. **Binding (loss clause, score.py rule):** records labelled `loss` that end retired: %d (usage-v1\'s 95: %d; the 13 since 1.2.0: %d). '
          'Valid retirements: %s.' % (x['loss_retired_total'], x['loss_retired_v1'], x['loss_retired_since120'],
                                      ', '.join('%s %s' % kv for kv in sorted(x['valid_states'].items()))))
        w('')
        w('**Binding for the valid clause; secondary for the loss clause.** Read by the earliest row that carries the key (the statement itself, not a later restatement that opens the same way): '
          '`loss` retired %d; valid: %s. W02 #236 reads active under usage-v1\'s rule only because its same-session restatement, '
          'which retired it, opens with the same words.' % (x['loss_retired_total_earliest_row'], ', '.join('%s %s' % kv for kv in sorted(x['valid_states_earliest_row'].items()))))
        w('')
        w('| usage-v1\'s 95, label:state | n |')
        w('|---|---|')
        for k, v in sorted(x['usage_v1_95'].items()):
            w('| %s | %d |' % (k, v))
        w('')
        w('| the 13 since 1.2.0, label:state | n |')
        w('|---|---|')
        for k, v in sorted(x['since_1_2_0_13'].items()):
            w('| %s | %d |' % (k, v))
        w('')
    if 'b2' in S:
        x = S['b2']
        w('B2, synthetic repositories.')
        w('')
        w('- reword (**binding: retirements of any kind**): %d of %d records retired (%d typed, secondary), %d `said:` records created.' % (x['reword']['retired'], x['reword']['records_before'], x['reword']['retired_typed'], x['reword']['said_records_created']))
        ab = x['aba']
        w('- A-B-A (binding: typed blocks): block stating A served %s (typed: %s); block stating B served %s (typed: %s); active decisions stating A %d, B %d.' % (
            ab['served_A_any_block'], ab['served_A_typed'], ab['served_B_any_block'], ab['served_B_typed'], ab['active_decisions_A'], ab['active_decisions_B']))
        for v in ('one_maintain', 'maintain_between'):
            r = x['revert_' + v]
            w('- revert, %s%s: records of the reverted commit %d, retired %d.' % (v.replace('_', ' '), ' (binding)' if v == 'one_maintain' else ' (secondary)', r['reverted_commit_records'], r['reverted_commit_retired']))
        w('')
    if 'b3' in S:
        w('B3, loop-8 held-out set (30 cells each). **Binding: `registered` (loop8/eval_all.py)**; `dated` is secondary. The noise clause reads: candidate retired_a not above the base level.')
        w('')
        w('| evaluator / arm / order | retired_a | kept_b | served_ok | old_served |')
        w('|---|---|---|---|---|')
        for k, v in sorted(S['b3'].items()):
            w('| %s | %s | %s | %s | %s |' % (k, v['retired_a'], v['kept_b'], v['served_ok'], v['old_served']))
        w('')
if c:
    S = c['splits']
    w('## C. Delivery (`c_delivery.py`)')
    w('')
    w('C1 and C2, the 150 labelled prompts replayed on rewound copies.')
    w('')
    w('| | design | held-out | all |')
    w('|---|---|---|---|')
    g = lambda k: [S[s]['c12'][k] for s in ('design', 'heldout', 'all')]
    w('| prompts / with a delivery | %s |' % ' | '.join('%d / %d' % (p, q) for p, q in zip(g('prompts'), g('prompts_with_delivery'))))
    w('| useful pairs returned | %s |' % ' | '.join(frac(p, q) for p, q in zip(g('useful_returned'), g('useful_labelled'))))
    w('| unrelated pairs returned | %s |' % ' | '.join(frac(p, q) for p, q in zip(g('unrelated_returned'), g('unrelated_labelled'))))
    w('| related pairs returned | %s |' % ' | '.join(frac(p, q) for p, q in zip(g('related_returned'), g('related_labelled'))))
    w('| harmful pairs returned | %s |' % ' | '.join(str(x) for x in g('harmful_returned')))
    w('| returned without a label | %s |' % ' | '.join('%d of %d' % (p, q) for p, q in zip(g('unlabelled_returned'), g('returned'))))
    if 'c2_same_ids' in S['all']['c12']:
        w('| C2 (binding): prompts with the same ids as `%s` / mean tokens | %s |' % (S['all']['c12']['c2_same_ids']['against'], ' | '.join('%d / %s' % (S[s]['c12']['c2_same_ids']['prompts'], S[s]['c12']['c2_same_ids']['mean_tokens_this']) for s in ('design', 'heldout', 'all'))))
    w('| mean estimated tokens a prompt (all prompts, secondary) | %s |' % ' | '.join(str(x) for x in g('mean_tokens')))
    w('| header + evidence share of block characters | %s |' % ' | '.join(str(x) for x in g('provenance_share')))
    w('')
    c1 = load('c_delivery', B1)
    if c1:
        x = c1['splits']['all']['c12']
        w('First labels: useful %s, unrelated %s, %s tokens a prompt.' % (frac(x['useful_returned'], x['useful_labelled']), frac(x['unrelated_returned'], x['unrelated_labelled']), x['mean_tokens']))
        w('')
    x = S['all']['c3']
    t1, t2, t3 = x['t1_cut_for_budget'], x['t2_after_compaction'], x['t3_stale_twin']
    w('C3, defects. Cut for budget at a session start (%d cut): offered again in the same session %d of %d, in a fresh session %d of %d. '
      'After a compaction: served again while the epoch line is pending %d of %d, after the next Stop %d of %d. '
      'Stale twin (twin retired as of each prompt, on the rewound copy): W02 %d of %d delivered prompts hold an episode whose typed twin is retired as superseded, L01 %d of %d.' % (
          t1['cut_at_start'], t1['same_session'], t1['tried'], t1['fresh_session'], t1['tried'],
          t2['epoch_line_pending']['served_again'], t2['epoch_line_pending']['first_blocks'], t2['after_next_stop']['served_again'], t2['after_next_stop']['first_blocks'],
          t3['W02:prompts_with_stale_twin'], t3['W02:delivered'], t3['L01:prompts_with_stale_twin'], t3['L01:delivered']))
    w('')
    y = x.get('t1_listed_in_catalogue')
    if y:
        w('C3, catalogue arm. Records the session start lists without a block (%d): offered again in the same session %d of %d, '
          'in a fresh session %d of %d.' % (y['listed_not_shown'], y['same_session'], y['tried'], y['fresh_session'], y['tried']))
        w('')
    w('C4, session starts replayed on rewound copies. Binding: neither the lenient nor the strict share of all slots may fall, and no active correction or invariant may be neither shown nor listed.')
    w('')
    w('| | design | held-out | all |')
    w('|---|---|---|---|')
    for form in ('blocks', 'catalogue'):
        w('| %s: slots (unlabelled) | %s |' % (form, ' | '.join('%d (%d)' % (S[s]['c4'][form]['slots'], S[s]['c4'][form]['unlabelled']) for s in ('design', 'heldout', 'all'))))
        w('| %s: worth the slot, lenient / strict | %s |' % (form, ' | '.join('%s / %s' % (S[s]['c4'][form]['share_lenient_of_labelled'], S[s]['c4'][form]['share_strict_of_labelled']) for s in ('design', 'heldout', 'all'))))
    w('| all slots, lenient / strict | %s |' % ' | '.join('%s / %s' % (S[s]['c4']['all_slots']['share_lenient_of_labelled'], S[s]['c4']['all_slots']['share_strict_of_labelled']) for s in ('design', 'heldout', 'all')))
    w('')
    cov = S['all']['c4']['coverage_today']
    w('| store (today\'s copy) | invariants active / shown / listed only | corrections active / shown / listed only |')
    w('|---|---|---|')
    for st, v in sorted(cov.items()):
        w('| %s | %d / %d / %d | %d / %d / %d |' % (st, v['invariant']['active'], v['invariant']['shown'], v['invariant']['listed_only'], v['correction']['active'], v['correction']['shown'], v['correction']['listed_only']))
    w('')
    x = S['all']['c5']
    w('C5, `muninn why`. usage-v2\'s questions (sha256 `%s`): Spanish %d of %d, English %d of %d. Records routed to a route that cannot return their kind: '
      '%d of %d returned (controls %d of %d). `--all` over %d retired records: one word %d, after "what about" %d. Gender-flipped words, W02: %d of %d in the top 8.' % (
          x['usage_v2_questions_sha256'], x['usage_v2']['spanish_reached'], x['usage_v2']['items'], x['usage_v2']['english_reached'], x['usage_v2']['items'],
          x['routed_away']['returned'], x['routed_away']['records'], x['routed_away']['control_returned'], x['routed_away']['control_records'],
          x['all_flag']['asked'], x['all_flag']['one_word_found'], x['all_flag']['what_about_found'], x['gender_flip_W02']['found_top8'], x['gender_flip_W02']['asked']))
    w('')
if d:
    x = d['splits']['all']
    w('## D. Removal readings (`d_removals.py`, the eleven store copies)')
    w('')
    w('- fire_ledger rows naming a dir, symbol, file, glob, keyword or tool cue: %d. Symbol rows: %d, in %d stores.' % (x['ledger_rows_naming_dir_symbol_file_or_tool_cue'], x['symbol_rows'], x['stores_with_symbols']))
    w('- `record_vec` rows: %d; stores with an embedding model set: %d.' % (x['record_vec_rows'], x['stores_with_embed_model']))
    w('- active `commit_linked` records: %s. Delivered by a hook: %s.' % (
        ', '.join('%s %d' % kv for kv in sorted(x['commit_linked_active'].items())),
        ', '.join('%s %d' % kv for kv in sorted(x['commit_linked_delivered_by_hook'].items())) or 'none'))
    w('- PostToolUse heartbeat rows: %d; turn-context logs: %d bytes.' % (x['posttooluse_heartbeats'], x['turn_context_bytes']))
    w('- ledger rows by channel: %s.' % ', '.join('%s %d' % kv for kv in sorted(x['ledger_by_channel'].items())))
    w('')
if e:
    x = e['splits']['all']
    w('## E. Latency (`e_perf.py`)')
    w('')
    if 'perf' in x:
        p = x['perf']
        w('`muninn-bench perf --strict`, %d runs, bench `%s`. Median over runs:' % (p['runs'], p['bench_sha256']))
        w('')
        w('| hook | p50 ms | p95 ms | p95 per run |')
        w('|---|---|---|---|')
        for h, v in p['hooks'].items():
            w('| %s | %s | %s | %s |' % (h, v['p50_median'], v['p95_median'], ', '.join(str(z) for z in v['p95_runs'])))
        w('')
        w('Process start p50 %s ms; ingest of 200 records %s ms. Contracts failed per run: %s.' % (p['process_start_p50_median'], p['ingest_200_ms_median'], '; '.join(', '.join(r) or 'none' for r in p['contracts_failed_per_run'])))
        w('')
    if 'stop_ingest_W02' in x:
        s = x['stop_ingest_W02']
        w('Stop with a one-turn ingest on a copy of W02, %d runs: median %s ms, p90 %s, min %s, max %s.' % (s['runs'], s['median_ms'], s['p90_ms'], s['min_ms'], s['max_ms']))
        w('')
w('## Reading notes')
w('')
w('- C1 counts every rendered block, including `commit_linked` blocks whose header carries the session `git`; the analysis '
  'parser skipped those, which is why its count of returned records is lower while the labelled figures are the same.')
w('- B1: an item missing from a replay arm is `absent` (its transcript is no longer on disk, or the arm never typed it); '
  'usage-v1 counts those as not measured. Compare arms, not this table with usage-v1\'s.')
w('- E was run on a working machine; process start alone moves between runs. Read E only from interleaved runs of '
  'two builds (`--against`), never against these absolute figures.')
w('- B and the fixed tests of C3 and C5 are not split; their figures sit under `all`.')
w('- Binding readings are those of the third amendment; `verdict.py <base> <candidate>` applies them.')
w('')
open(os.path.join(HERE, 'BASELINE.md'), 'w', newline='\n').write('\n'.join(L))
print('\n'.join(L))
